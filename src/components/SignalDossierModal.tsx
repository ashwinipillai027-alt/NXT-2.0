import React, { useState } from 'react';
import { Signal, TAXONOMY_CONFIG, ValidationItem } from '../types/signal';
import {
  X,
  ArrowUpRight,
  Bookmark,
  Download,
  CheckCircle2,
  Circle,
  TrendingUp,
  ShieldCheck,
  AlertTriangle,
  Lightbulb,
  MessageSquareQuote,
  Sparkles,
  Copy,
  Check,
} from 'lucide-react';

interface SignalDossierModalProps {
  signal: Signal | null;
  onClose: () => void;
  isSaved: boolean;
  onToggleSave: (signalId: string) => void;
  onUpdateValidationChecklist: (signalId: string, items: ValidationItem[]) => void;
}

export const SignalDossierModal: React.FC<SignalDossierModalProps> = ({
  signal,
  onClose,
  isSaved,
  onToggleSave,
  onUpdateValidationChecklist,
}) => {
  const [copied, setCopied] = useState(false);

  if (!signal) return null;

  const taxonomy =
    TAXONOMY_CONFIG[signal.taxonomyCategory] || TAXONOMY_CONFIG.sentiment;
  const isQualified = signal.qualityScore >= 0.75;

  const handleToggleValidation = (itemId: string) => {
    const updated = signal.validationChecklist.map((item) =>
      item.id === itemId ? { ...item, checked: !item.checked } : item
    );
    onUpdateValidationChecklist(signal.id, updated);
  };

  const handleExportMarkdown = () => {
    const md = `# Problem Intelligence Dossier: ${signal.title}
**Theme:** ${signal.theme} (${taxonomy.label})
**Silhouette Quality Score:** ${signal.qualityScore.toFixed(2)} (${isQualified ? 'QUALIFIED ≥0.75' : 'MONITORING ONLY'})
**Supporting Posts:** ${signal.supportingPosts}
**Communities:** ${signal.communities.join(', ')}
**Time Period:** ${signal.timePeriod}
**Momentum:** ${signal.acceleration}
**Source URL:** ${signal.sourceUrl}

---

## 1. Executive Synthesis
${signal.summary}

## 2. Structural Root Causes
${signal.rootCauses.map((rc, i) => `${i + 1}. ${rc}`).join('\n')}

## 3. Verbatim Community Evidence
${signal.representativeQuotes
  .map(
    (q) => `> "${q.text}"\n> — ${q.author} in ${q.community} (${q.upvotes} upvotes, ${q.date})`
  )
  .join('\n\n')}

## 4. What to Build Next (Market Opportunity)
- **Problem Statement:** ${signal.marketOpportunity.problemStatement}
- **Proposed Architecture:** ${signal.marketOpportunity.whatToBuild}
- **Beachhead Segment:** ${signal.marketOpportunity.targetBeachhead}
- **Willingness to Pay:** ${signal.marketOpportunity.willingnessToPaySignal}
- **TAM Estimation:** ${signal.marketOpportunity.tamEstimate}
- **Engineering Complexity:** ${signal.marketOpportunity.difficultyLevel}

## 5. Validation Checklist Status
${signal.validationChecklist
  .map((v) => `- [${v.checked ? 'x' : ' '}] ${v.label}: ${v.rationale}`)
  .join('\n')}

---
*Generated by NXT Executive Intelligence Interface*
`;

    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `NXT-Dossier-${signal.id}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleCopySummary = () => {
    const text = `[NXT Signal] ${signal.title}\nQuality Score: ${signal.qualityScore.toFixed(2)} (${signal.supportingPosts} posts across ${signal.communities.join(', ')})\nSummary: ${signal.summary}\nWhat to Build: ${signal.marketOpportunity.whatToBuild}`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 overflow-y-auto bg-[#171717]/35 backdrop-blur-[2px] flex justify-end">
      {/* Slide-over panel */}
      <div className="w-full max-w-2xl bg-[#ffffff] min-h-screen border-l border-[#e7e5e0] shadow-2xl flex flex-col justify-between animate-in slide-in-from-right duration-250">
        <div>
          {/* Header toolbar */}
          <div className="sticky top-0 z-10 bg-[#faf9f5] border-b border-[#e7e5e0] px-6 py-4 flex items-center justify-between gap-4">
            <div className="flex items-center gap-2">
              <span
                className="text-[11px] font-instrument font-semibold px-2 py-0.5 rounded-[4px]"
                style={{ backgroundColor: taxonomy.bg, color: taxonomy.text }}
              >
                {signal.theme}
              </span>
              <span className="text-xs text-[#737373] font-mono tabular-nums">
                ID: {signal.id}
              </span>
            </div>

            <div className="flex items-center gap-2">
              <button
                onClick={() => onToggleSave(signal.id)}
                title={isSaved ? 'Saved to shortlist' : 'Save to shortlist'}
                className="p-1.5 rounded-lg border border-[#e7e5e0] text-[#5f5e5e] hover:text-[#1b1c1a] hover:bg-[#ffffff] transition-colors"
              >
                <Bookmark
                  className={`w-4 h-4 ${isSaved ? 'fill-[#1b1c1a] text-[#1b1c1a]' : ''}`}
                />
              </button>
              <button
                onClick={handleCopySummary}
                title="Copy signal brief"
                className="p-1.5 rounded-lg border border-[#e7e5e0] text-[#5f5e5e] hover:text-[#1b1c1a] hover:bg-[#ffffff] transition-colors"
              >
                {copied ? <Check className="w-4 h-4 text-[#4d6700]" /> : <Copy className="w-4 h-4 text-[#5f5e5e]" />}
              </button>
              <button
                onClick={handleExportMarkdown}
                title="Export as Markdown dossier"
                className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg border border-[#e7e5e0] text-xs font-medium text-[#1b1c1a] hover:bg-[#ffffff] transition-colors"
              >
                <Download className="w-3.5 h-3.5" />
                <span>Export Brief</span>
              </button>
              <button
                onClick={onClose}
                className="p-1.5 text-[#737373] hover:text-[#1b1c1a] rounded-lg transition-colors ml-1"
              >
                <X className="w-5 h-5" />
              </button>
            </div>
          </div>

          {/* Dossier Body */}
          <div className="p-6 sm:p-8 space-y-8">
            {/* Title & Quality Banner */}
            <div>
              <div className="flex items-center gap-2 text-xs font-instrument text-[#5f5e5e] mb-2">
                <span>Problem Dossier</span>
                <span>·</span>
                <span>{signal.timePeriod}</span>
                <span>·</span>
                <span className="font-mono tabular-nums">{signal.supportingPosts} posts</span>
              </div>
              <h2 className="font-editorial text-2xl sm:text-3xl font-medium text-[#1b1c1a] leading-tight">
                {signal.title}
              </h2>
            </div>

            {/* Quality Telemetry Panel */}
            <div
              className={`rounded-xl border p-4.5 flex flex-col sm:flex-row sm:items-center justify-between gap-4 ${
                isQualified
                  ? 'bg-[#c8f169]/10 border-[#4d6700]/30'
                  : 'bg-[#ffdad6]/20 border-[#ba1a1a]/30'
              }`}
            >
              <div>
                <div className="flex items-center gap-2">
                  {isQualified ? (
                    <ShieldCheck className="w-4 h-4 text-[#4d6700]" />
                  ) : (
                    <AlertTriangle className="w-4 h-4 text-[#ba1a1a]" />
                  )}
                  <span className="text-xs font-instrument font-semibold uppercase tracking-wider text-[#1b1c1a]">
                    {isQualified ? 'Statistically Qualified Signal' : 'Monitoring Cluster Only'}
                  </span>
                </div>
                <p className="text-xs text-[#5f5e5e] font-instrument mt-1">
                  {signal.qualityDefinition}
                </p>
              </div>

              <div className="flex items-center gap-6 shrink-0 font-mono tabular-nums">
                <div>
                  <div className="text-[10px] text-[#737373] uppercase">Silhouette</div>
                  <div
                    className={`text-xl font-bold ${
                      isQualified ? 'text-[#4d6700]' : 'text-[#ba1a1a]'
                    }`}
                  >
                    {signal.qualityScore.toFixed(2)}
                  </div>
                </div>
                <div>
                  <div className="text-[10px] text-[#737373] uppercase">Velocity</div>
                  <div className="text-xl font-bold text-[#1b1c1a] flex items-center gap-1">
                    <TrendingUp className="w-4 h-4 text-[#4d6700]" />
                    {signal.acceleration}
                  </div>
                </div>
              </div>
            </div>

            {/* Section 1: Qualitative Synthesis */}
            <div>
              <h3 className="text-xs font-instrument uppercase tracking-[0.04em] font-semibold text-[#737373] mb-2">
                01. Qualitative Synthesis
              </h3>
              <p className="font-instrument text-base text-[#1b1c1a] leading-relaxed">
                {signal.summary}
              </p>
            </div>

            {/* Section 2: Structural Root Causes */}
            <div>
              <h3 className="text-xs font-instrument uppercase tracking-[0.04em] font-semibold text-[#737373] mb-3">
                02. Structural Root Causes
              </h3>
              <div className="space-y-2.5">
                {signal.rootCauses.map((cause, idx) => (
                  <div
                    key={idx}
                    className="p-3 rounded-lg border border-[#e7e5e0] bg-[#faf9f5] flex items-start gap-3"
                  >
                    <span className="font-mono text-xs font-bold text-[#4d6700] mt-0.5">
                      0{idx + 1}
                    </span>
                    <p className="text-xs sm:text-sm text-[#1b1c1a] font-instrument leading-relaxed">
                      {cause}
                    </p>
                  </div>
                ))}
              </div>
            </div>

            {/* Section 3: Verbatim Community Evidence */}
            <div>
              <div className="flex items-center justify-between mb-3">
                <h3 className="text-xs font-instrument uppercase tracking-[0.04em] font-semibold text-[#737373]">
                  03. Verbatim Community Dialogue
                </h3>
                <a
                  href={signal.sourceUrl}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="text-xs text-[#4d6700] hover:text-[#1b1c1a] inline-flex items-center gap-1 font-instrument underline"
                >
                  <span>Open Thread</span>
                  <ArrowUpRight className="w-3.5 h-3.5" />
                </a>
              </div>
              <div className="space-y-3">
                {signal.representativeQuotes.map((q) => (
                  <blockquote
                    key={q.id}
                    className="p-4 rounded-xl border border-[#e7e5e0] bg-[#ffffff] relative"
                  >
                    <MessageSquareQuote className="w-4 h-4 text-[#737373] mb-1.5 opacity-60" />
                    <p className="font-instrument text-xs sm:text-sm text-[#1b1c1a] leading-relaxed italic">
                      "{q.text}"
                    </p>
                    <div className="mt-3 pt-2.5 border-t border-[#e7e5e0] flex items-center justify-between text-[11px] text-[#737373] font-instrument">
                      <span className="font-medium text-[#1b1c1a]">
                        {q.author} in <span className="text-[#4d6700]">{q.community}</span>
                      </span>
                      <span className="font-mono tabular-nums">
                        ▲ {q.upvotes} upvotes · {q.date}
                      </span>
                    </div>
                  </blockquote>
                ))}
              </div>
            </div>

            {/* Section 4: What to Build Next (Market Opportunity Blueprint) */}
            <div className="rounded-xl border border-[#1b1c1a] bg-[#faf9f5] p-5 sm:p-6">
              <div className="flex items-center gap-2 mb-3">
                <span className="p-1 rounded bg-[#c8f169] text-[#1b1c1a]">
                  <Sparkles className="w-4 h-4 stroke-[2.2]" />
                </span>
                <h3 className="text-sm font-instrument font-bold text-[#1b1c1a] uppercase tracking-wide">
                  Strategic Recommendation: What to Build Next
                </h3>
              </div>

              <div className="space-y-4 text-xs sm:text-sm font-instrument">
                <div>
                  <div className="text-[11px] font-semibold text-[#737373] uppercase mb-1">
                    Problem Hypothesis
                  </div>
                  <p className="text-[#1b1c1a] leading-relaxed">
                    {signal.marketOpportunity.problemStatement}
                  </p>
                </div>

                <div className="bg-[#ffffff] border border-[#e7e5e0] rounded-lg p-3.5">
                  <div className="text-[11px] font-semibold text-[#4d6700] uppercase mb-1">
                    Proposed Product Vector
                  </div>
                  <p className="text-[#1b1c1a] font-medium leading-relaxed">
                    {signal.marketOpportunity.whatToBuild}
                  </p>
                </div>

                <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 pt-1">
                  <div className="bg-[#ffffff] border border-[#e7e5e0] rounded-lg p-3">
                    <span className="text-[10px] text-[#737373] uppercase font-semibold block mb-0.5">
                      Beachhead User Segment
                    </span>
                    <span className="text-xs text-[#1b1c1a] font-medium">
                      {signal.marketOpportunity.targetBeachhead}
                    </span>
                  </div>

                  <div className="bg-[#ffffff] border border-[#e7e5e0] rounded-lg p-3">
                    <span className="text-[10px] text-[#737373] uppercase font-semibold block mb-0.5">
                      Willingness-to-Pay Signal
                    </span>
                    <span className="text-xs text-[#1b1c1a] font-medium">
                      {signal.marketOpportunity.willingnessToPaySignal}
                    </span>
                  </div>
                </div>

                <div className="flex items-center justify-between pt-2 border-t border-[#e7e5e0] text-xs">
                  <span className="text-[#737373]">
                    Estimated TAM: <strong>{signal.marketOpportunity.tamEstimate}</strong>
                  </span>
                  <span className="text-[#737373]">
                    Build Complexity:{' '}
                    <strong
                      className={
                        signal.marketOpportunity.difficultyLevel === 'High'
                          ? 'text-[#ba1a1a]'
                          : 'text-[#4d6700]'
                      }
                    >
                      {signal.marketOpportunity.difficultyLevel}
                    </strong>
                  </span>
                </div>
              </div>
            </div>

            {/* Section 5: Problem Validation Checklist */}
            <div>
              <div className="flex items-center justify-between mb-3">
                <h3 className="text-xs font-instrument uppercase tracking-[0.04em] font-semibold text-[#737373]">
                  05. Hypothesis Validation Checklist
                </h3>
                <span className="text-[11px] text-[#737373] font-mono tabular-nums">
                  {signal.validationChecklist.filter((v) => v.checked).length} of{' '}
                  {signal.validationChecklist.length} Verified
                </span>
              </div>

              <div className="space-y-2">
                {signal.validationChecklist.map((item) => (
                  <button
                    key={item.id}
                    onClick={() => handleToggleValidation(item.id)}
                    className={`w-full text-left p-3 rounded-lg border transition-all flex items-start gap-3 cursor-pointer ${
                      item.checked
                        ? 'bg-[#c8f169]/10 border-[#4d6700]/40'
                        : 'bg-[#ffffff] border-[#e7e5e0] hover:border-[#757966]'
                    }`}
                  >
                    <div className="mt-0.5 shrink-0">
                      {item.checked ? (
                        <CheckCircle2 className="w-4 h-4 text-[#4d6700]" />
                      ) : (
                        <Circle className="w-4 h-4 text-[#737373]" />
                      )}
                    </div>
                    <div>
                      <div
                        className={`text-xs font-instrument font-medium ${
                          item.checked ? 'text-[#1b1c1a]' : 'text-[#5f5e5e]'
                        }`}
                      >
                        {item.label}
                      </div>
                      <div className="text-[11px] text-[#737373] font-instrument mt-0.5">
                        {item.rationale}
                      </div>
                    </div>
                  </button>
                ))}
              </div>
            </div>
          </div>
        </div>

        {/* Footer actions */}
        <div className="sticky bottom-0 z-10 bg-[#faf9f5] border-t border-[#e7e5e0] p-4 sm:p-6 flex items-center justify-between gap-3">
          <a
            href={signal.sourceUrl}
            target="_blank"
            rel="noopener noreferrer"
            className="text-xs font-instrument font-medium text-[#1b1c1a] hover:underline inline-flex items-center gap-1"
          >
            <span>Open Community Thread</span>
            <ArrowUpRight className="w-3.5 h-3.5" />
          </a>

          <div className="flex items-center gap-2">
            <button
              onClick={handleExportMarkdown}
              className="px-3.5 py-2 text-xs font-medium text-[#1b1c1a] bg-[#ffffff] border border-[#e7e5e0] hover:bg-[#efeeea] rounded-lg transition-colors cursor-pointer"
            >
              Export Brief (.md)
            </button>
            <button
              onClick={onClose}
              className="px-4 py-2 text-xs font-medium text-[#ffffff] bg-[#171717] hover:bg-[#2e2e2e] rounded-lg transition-colors cursor-pointer"
            >
              Done
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
